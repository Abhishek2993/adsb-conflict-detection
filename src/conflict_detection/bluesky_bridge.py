"""Export encounters to BlueSky scenario files and verify them in the simulator.

For each conflict event two ``.scn`` files are written:

* ``<event>_unresolved.scn``: both aircraft created at their predicted states
  at the time of the first alert, flying straight (climbing/descending ones
  keep their vertical rate up to the level reached at the end of the run);
* ``<event>_resolved.scn``: the same plus the resolution command chosen by
  :mod:`conflict_detection.resolve` (``HDG``, ``SPD`` or ``ALT``), issued at
  time zero.

Each file disables BlueSky's own conflict detection and resolution
(``ASAS OFF``, ``RESO OFF``), creates a state logger (``CRELOG``) and ends with
``HOLD``. :func:`run_scenarios` runs the files headless (BlueSky ``detached``
mode, in a separate Python process so BlueSky's global state and console
output stay out of the pipeline) and :func:`verify_logs` reads the logged
states back to check whether separation was lost.

BlueSky needs an aircraft type for its performance model and ADS-B does not
carry one. All aircraft are created as A333 because, of the common types in
BlueSky's OpenAP model, it has the highest ceiling (41,100 ft); encounters
that need a higher level are exported but marked as not simulable.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from .config import Config
from .cpa import in_los
from .geo import LocalFrame
from .units import FT, NM, m_to_ft, ms_to_fpm, ms_to_kt, tas_to_cas, unit_to_heading

AIRCRAFT_TYPE = "A333"
TYPE_CEILING_FT = 41000.0
LOGGER = "CDRLOG"
LOG_VARS = "traf.id, traf.lat, traf.lon, traf.alt, traf.tas, traf.gs, traf.trk, traf.vs"
LOG_DT_S = 1.0
MARGIN_S = 60.0


def _hms(t: float) -> str:
    h, rem = divmod(float(t), 3600)
    m, s = divmod(rem, 60)
    return f"{int(h):02d}:{int(m):02d}:{s:05.2f}"


def acid_for(callsign: str, icao24: str, taken: set[str]) -> str:
    """A BlueSky-safe aircraft id: the callsign if usable, else ``A`` + ICAO address."""
    cs = re.sub(r"[^A-Z0-9]", "", str(callsign).upper())
    acid = cs if cs and cs not in taken else f"A{icao24.upper()}"
    taken.add(acid)
    return acid


@dataclass
class AircraftInit:
    """Initial state of one aircraft in a BlueSky scenario."""

    acid: str
    icao24: str
    lat: float
    lon: float
    heading_deg: float
    altitude_ft: float
    tas_kt: float
    cas_kt: float
    vs_fpm: float
    target_altitude_ft: float

    def commands(self) -> list[str]:
        """``CRE`` (and, if climbing or descending, ``ALT``) commands."""
        cmds = [
            f"CRE {self.acid} {AIRCRAFT_TYPE} {self.lat:.6f} {self.lon:.6f} "
            f"{self.heading_deg:.1f} {self.altitude_ft:.0f} {self.cas_kt:.1f}"
        ]
        if abs(self.vs_fpm) >= 100:
            cmds.append(f"ALT {self.acid} {self.target_altitude_ft:.0f} {self.vs_fpm:.0f}")
        return cmds


def aircraft_init(
    state: pd.Series, acid: str, frame: LocalFrame, duration_s: float
) -> AircraftInit:
    """Convert a predicted state (local frame, SI) to BlueSky initial conditions."""
    lat, lon = frame.to_latlon(state.x, state.y)
    tas = float(np.hypot(state.vx, state.vy))
    alt_ft = float(m_to_ft(state.z))
    vs_fpm = float(ms_to_fpm(state.vz))
    return AircraftInit(
        acid=acid,
        icao24=str(state.icao24),
        lat=float(lat),
        lon=float(lon),
        heading_deg=float(unit_to_heading(state.vx, state.vy)),
        altitude_ft=alt_ft,
        tas_kt=float(ms_to_kt(tas)),
        cas_kt=float(ms_to_kt(tas_to_cas(tas, state.z))),
        vs_fpm=vs_fpm,
        target_altitude_ft=alt_ft + vs_fpm * duration_s / 60.0,
    )


def resolution_command(res: pd.Series, init: AircraftInit) -> str:
    """BlueSky command implementing a resolution for the manoeuvring aircraft."""
    if res.kind == "heading":
        return f"HDG {init.acid} {res.new_heading_deg:.1f}"
    if res.kind == "speed":
        new_tas = res.new_speed_kt * (1852 / 3600)
        cas = ms_to_kt(tas_to_cas(new_tas, init.altitude_ft * FT))
        return f"SPD {init.acid} {cas:.1f}"
    if res.kind == "level":
        return f"ALT {init.acid} {res.new_altitude_ft:.0f} {np.sign(res.value) * 1500:.0f}"
    raise ValueError(f"no BlueSky command for resolution kind {res.kind!r}")


def scenario_text(
    inits: list[AircraftInit],
    duration_s: float,
    title: str,
    extra: list[str] | None = None,
) -> str:
    """Full ``.scn`` file content."""
    t0 = _hms(0)
    lines = [
        f"# {title}",
        "# Generated by adsb-conflict-detection. Times are relative to the first alert.",
        f"# Aircraft type {AIRCRAFT_TYPE} is a stand-in: ADS-B does not report the type.",
        f"{t0}>ASAS OFF",
        f"{t0}>RESO OFF",
    ]
    for init in inits:
        lines += [f"{t0}>{c}" for c in init.commands()]
    lines += [
        f"{t0}>CRELOG {LOGGER} {LOG_DT_S} {title}",
        f"{t0}>{LOGGER} ADD {LOG_VARS}",
        f"{t0}>{LOGGER} ON",
    ]
    lines += [f"{t0}>{c}" for c in extra or []]
    lines += [f"{_hms(duration_s)}>{LOGGER} OFF", f"{_hms(duration_s)}>HOLD"]
    return "\n".join(lines) + "\n"


@dataclass
class EncounterFiles:
    """Exported scenario files of one conflict event."""

    event_id: str
    icao_a: str
    icao_b: str
    acid_a: str
    acid_b: str
    unresolved: str
    resolved: str | None
    command: str | None
    duration_s: float
    simulable: bool
    note: str


def export_encounter(
    event: pd.Series,
    states_at_t: pd.DataFrame,
    resolution: pd.Series | None,
    frame: LocalFrame,
    out_dir: str | Path,
    cfg: Config | None = None,
) -> EncounterFiles:
    """Write the unresolved and (if any) resolved scenario of one event."""
    cfg = cfg or Config()
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    duration = cfg.horizon_s + MARGIN_S
    st = states_at_t.set_index("icao24", drop=False)
    taken: set[str] = set()
    inits = []
    for icao in (event.icao_a, event.icao_b):
        row = st.loc[icao]
        inits.append(aircraft_init(row, acid_for(row.callsign, icao, taken), frame, duration))
    top = max(max(i.altitude_ft, i.target_altitude_ft) for i in inits)
    note = ""
    if resolution is not None and resolution.kind == "level":
        top = max(top, float(resolution.new_altitude_ft))
    simulable = top <= TYPE_CEILING_FT
    if not simulable:
        note = f"needs {top:.0f} ft, above the {AIRCRAFT_TYPE} ceiling in BlueSky"
    title = f"{event.event_id} {inits[0].acid} vs {inits[1].acid}"
    unres = out / f"{event.event_id}_unresolved.scn"
    unres.write_text(scenario_text(inits, duration, f"{title} (no resolution)"))
    res_path, command = None, None
    if resolution is not None and bool(resolution.resolved):
        own = inits[0] if resolution.manoeuvring == event.icao_a else inits[1]
        command = resolution_command(resolution, own)
        res_path = out / f"{event.event_id}_resolved.scn"
        res_path.write_text(
            scenario_text(inits, duration, f"{title} ({resolution.manoeuvre})", [command])
        )
    return EncounterFiles(
        event_id=str(event.event_id),
        icao_a=str(event.icao_a),
        icao_b=str(event.icao_b),
        acid_a=inits[0].acid,
        acid_b=inits[1].acid,
        unresolved=str(unres),
        resolved=None if res_path is None else str(res_path),
        command=command,
        duration_s=duration,
        simulable=simulable,
        note=note,
    )


def export_all(
    events: pd.DataFrame,
    states: pd.DataFrame,
    resolutions: pd.DataFrame,
    frame: LocalFrame,
    out_dir: str | Path,
    cfg: Config | None = None,
) -> pd.DataFrame:
    """Export every event and write ``manifest.json`` next to the files."""
    out = Path(out_dir)
    by_time = dict(tuple(states.groupby("t_eval")))
    res = resolutions.set_index("event_id") if len(resolutions) else None
    rows = []
    for _, ev in events.iterrows():
        r = res.loc[ev.event_id] if res is not None and ev.event_id in res.index else None
        rows.append(asdict(export_encounter(ev, by_time[ev.t_first], r, frame, out, cfg)))
    manifest = pd.DataFrame(rows)
    out.mkdir(parents=True, exist_ok=True)
    (out / "manifest.json").write_text(json.dumps(rows, indent=2))
    return manifest


def bluesky_available() -> bool:
    """True if the ``bluesky`` package can be imported."""
    try:
        import bluesky  # noqa: F401
    except Exception:  # pragma: no cover - depends on the environment
        return False
    return True


def _run_in_process(scn_files: list[str], workdir: str) -> dict[str, str]:  # pragma: no cover
    """Run scenario files headless in *this* process. Returns {scn: log file}."""
    import bluesky as bs

    Path(workdir).mkdir(parents=True, exist_ok=True)
    bs.init(mode="sim", detached=True, workdir=workdir)
    from bluesky import sim, stack

    outdir = Path(workdir) / "output"
    logs: dict[str, str] = {}
    for scn in scn_files:
        before = set(outdir.glob("*.log"))
        text = Path(scn).read_text()
        end = max(_parse_time(line.split(">")[0]) for line in text.splitlines() if ">" in line)
        stack.stack(f"IC {Path(scn).resolve()}")
        sim.step()
        # The scenario ends with HOLD at `end`; a paused simulation no longer
        # advances simt, so stop at `end` (with a step budget as a safety net).
        budget = int((end + 10.0) / 0.05) * 2
        while sim.simt < end and budget > 0:
            sim.step()
            budget -= 1
        stack.stack(f"{LOGGER} OFF")
        sim.step()
        new = sorted(set(outdir.glob("*.log")) - before)
        if new:
            logs[scn] = str(new[-1])
    return logs


def _parse_time(text: str) -> float:
    h, m, s = text.strip().split(":")
    return int(h) * 3600 + int(m) * 60 + float(s)


def run_scenarios(scn_files: list[str], workdir: str | Path) -> dict[str, str]:
    """Run scenario files headless in a separate process; returns {scn: log file}.

    Raises ``RuntimeError`` if BlueSky is not installed or the run fails.
    """
    if not bluesky_available():
        raise RuntimeError("bluesky-simulator is not installed (pip install -e .[bluesky])")
    workdir = Path(workdir).resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    job = workdir / "job.json"
    job.write_text(json.dumps({"scn": [str(Path(s).resolve()) for s in scn_files]}))
    proc = subprocess.run(
        [sys.executable, "-m", "conflict_detection.bluesky_bridge", str(job), str(workdir)],
        capture_output=True,
        text=True,
        check=False,
    )
    (workdir / "bluesky_stdout.txt").write_text(proc.stdout + "\n" + proc.stderr)
    result = workdir / "logs.json"
    if proc.returncode != 0 or not result.exists():
        raise RuntimeError(f"BlueSky run failed, see {workdir / 'bluesky_stdout.txt'}")
    logs = json.loads(result.read_text())
    return {_key(k): v for k, v in logs.items()}


def _key(scn: str | Path) -> str:
    """Canonical dictionary key for a scenario file (absolute, resolved path)."""
    return str(Path(scn).resolve())


def read_log(path: str | Path) -> pd.DataFrame:
    """Parse a ``CDRLOG`` file written by BlueSky's ``CRELOG`` logger."""
    df = pd.read_csv(
        path,
        comment="#",
        header=None,
        names=["simt", "acid", "lat", "lon", "alt_m", "tas_ms", "gs_ms", "trk_deg", "vs_ms"],
        skipinitialspace=True,
    )
    df["acid"] = df.acid.astype(str).str.strip()
    return df


def separation_from_log(log: pd.DataFrame, acid_a: str, acid_b: str, cfg: Config | None = None):
    """Minimum separation between two aircraft in a BlueSky log.

    Returns a dict with ``los`` (bool), ``min_hdist_nm``, ``vsep_at_min_ft``,
    ``t_min_s`` and ``los_duration_s``.
    """
    cfg = cfg or Config()
    a = log[log.acid == acid_a].set_index("simt")
    b = log[log.acid == acid_b].set_index("simt")
    j = a.join(b, lsuffix="_a", rsuffix="_b", how="inner")
    if j.empty:
        raise ValueError(f"{acid_a} and {acid_b} never logged together")
    frame = LocalFrame(float(j.lat_a.iloc[0]), float(j.lon_a.iloc[0]))
    xa, ya = frame.to_xy(j.lat_a.to_numpy(), j.lon_a.to_numpy())
    xb, yb = frame.to_xy(j.lat_b.to_numpy(), j.lon_b.to_numpy())
    hd = np.hypot(xa - xb, ya - yb)
    vd = np.abs(j.alt_m_a.to_numpy() - j.alt_m_b.to_numpy())
    los = in_los(hd, vd, cfg.separation.horizontal_m, cfg.separation.vertical_m)
    k = int(np.argmin(hd))
    dt = float(np.median(np.diff(j.index.to_numpy()))) if len(j) > 1 else 0.0
    return {
        "los": bool(los.any()),
        "min_hdist_nm": float(hd[k] / NM),
        "vsep_at_min_ft": float(vd[k] / FT),
        "t_min_s": float(j.index[k]),
        "los_duration_s": float(los.sum() * dt),
    }


def verify_logs(
    manifest: pd.DataFrame, logs: dict[str, str], cfg: Config | None = None
) -> pd.DataFrame:
    """Compare unresolved and resolved BlueSky runs of every exported encounter."""
    cfg = cfg or Config()
    rows = []
    for _, m in manifest.iterrows():
        row = {"event_id": m.event_id, "acid_a": m.acid_a, "acid_b": m.acid_b,
               "command": m.command, "simulable": bool(m.simulable)}  # fmt: skip
        for label in ("unresolved", "resolved"):
            scn = m[label]
            key = _key(scn) if isinstance(scn, str) else None
            if key and key in logs:
                sep = separation_from_log(read_log(logs[key]), m.acid_a, m.acid_b, cfg)
                row.update({f"{label}_{k}": v for k, v in sep.items()})
                row[f"{label}_log"] = logs[key]
        rows.append(row)
    out = pd.DataFrame(rows)
    if "unresolved_los" in out and "resolved_los" in out:
        out["conflict_reproduced"] = out.unresolved_los.astype("boolean")
        out["resolution_success"] = (~out.resolved_los.astype("boolean")).where(
            out.resolved_los.notna()
        )
    return out


def find_manual_logs(manifest: pd.DataFrame, log_dir: str | Path) -> dict[str, str]:
    """Match logs from a manual BlueSky run (``CDRLOG_<scenario>_<time>.log``) to scenarios."""
    logs: dict[str, str] = {}
    files = sorted(Path(log_dir).glob(f"{LOGGER}_*.log"))
    for _, m in manifest.iterrows():
        for label in ("unresolved", "resolved"):
            scn = m[label]
            if not isinstance(scn, str):
                continue
            stem = Path(scn).stem
            hits = [f for f in files if f.name.startswith(f"{LOGGER}_{stem}_")]
            if hits:
                logs[_key(scn)] = str(hits[-1])
    return logs


def manual_run_instructions(scn_dir: str | Path) -> str:
    """Markdown instructions for running the exported scenarios by hand."""
    return f"""# Running the exported scenarios in BlueSky by hand

1. Install BlueSky with its GUI: `pip install "bluesky-simulator[full]==1.1.1"`
2. Start it from this folder: `bluesky` (or `python -m bluesky`).
3. In the BlueSky console, load one scenario and fast-forward:
   `IC {Path(scn_dir).resolve()}/C001_unresolved.scn` then `FF`.
   Each scenario stops itself (`HOLD`) after the look-ahead horizon plus 60 s.
4. Repeat for the `_resolved.scn` file of the same event. Every run writes a
   state log `CDRLOG_<scenario>_<date>.log` to BlueSky's `output/` folder.
5. Score the logs against the manifest:

   ```bash
   python -m conflict_detection bluesky-verify \\
       --manifest {Path(scn_dir) / "manifest.json"} --logs <bluesky output folder>
   ```
"""


def main(argv: list[str] | None = None) -> None:  # pragma: no cover - runs in a subprocess
    """Subprocess entry point: ``python -m conflict_detection.bluesky_bridge job.json workdir``."""
    args = argv if argv is not None else sys.argv[1:]
    job, workdir = Path(args[0]), args[1]
    scn = json.loads(job.read_text())["scn"]
    logs = _run_in_process(scn, workdir)
    (Path(workdir) / "logs.json").write_text(json.dumps(logs, indent=2))


if __name__ == "__main__":  # pragma: no cover
    main()
